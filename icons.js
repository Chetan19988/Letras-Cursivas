export function iconSvg(name, className = '') {
  const body = PATHS[name];
  if (!body) return '';
  const cls = `lucide lucide-${name}${className ? ` ${className}` : ''}`;
  return `<svg class="${cls}" xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

// Replace <i data-lucide="name"> placeholders with the inline SVG.
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-lucide]').forEach((el) => {
    const markup = iconSvg(el.getAttribute('data-lucide'), el.className || '');
    if (!markup) return;
    const template = document.createElement('template');
    template.innerHTML = markup;
    el.replaceWith(template.content.firstElementChild);
  });
}
